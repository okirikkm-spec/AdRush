package com.adrenrush.web.enums;

/** Состояние найденной парсером позиции в приёмке (см. {@code ParsedCandidate}). */
public enum CandidateStatus {

    /** Ждёт решения администратора — предлагается к добавлению в каталог. */
    PENDING,

    /** Администратор отклонил позицию: остаётся в списке, но при новых проходах галочка не ставится. */
    IGNORED
}
