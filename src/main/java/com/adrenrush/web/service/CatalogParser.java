package com.adrenrush.web.service;

import java.util.List;

/**
 * Парсер каталога сайта-источника. Парсеры НЕ пишут в базу: они только приносят найденные позиции,
 * а решение о добавлении принимает администратор в окне приёмки (см. {@link ParserStagingService}).
 */
public interface CatalogParser {

    /** Метка источника для админки и для поля {@code source} в приёмке, например «Red Bull». */
    String source();

    /** Выключенные в конфиге источники не опрашиваются ни по расписанию, ни вручную. */
    boolean isEnabled();

    /**
     * Обходит каталог источника и возвращает найденные позиции. Сеть — да, запись в базу — нет.
     * Ошибки обхода парсер логирует сам и возвращает пустой список.
     */
    List<ParsedItem> collect();
}
